export const parseFolderDate = (folderName, defaultFolderName, fallbackName = 'İndirmeler') => {
  if (folderName === defaultFolderName || folderName === fallbackName) return Number.MAX_SAFE_INTEGER;
  
  const match = folderName.match(/^(\d{2})-(\d{2})-(\d{4})(?:\s+\((\d+)\))?/);
  if (!match) return 0;
  
  const [_, month, day, year, count] = match;
  const dateNum = parseInt(year) * 10000 + parseInt(month) * 100 + parseInt(day);
  const countNum = count ? parseInt(count) : 0;
  
  return dateNum * 1000 + countNum;
};
